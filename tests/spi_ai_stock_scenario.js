const assert=require('node:assert/strict');
(async()=>{
const {openDb}=await import('../server/_lib/db.mjs'),{ask,stockScenario}=await import('../spi/ai/ask.js'),{resolveContext}=await import('../spi/ai/context.js');
const db=openDb();
assert.equal(stockScenario('What if we cut stock by 20%?')[1].stock_multiplier,.8);
assert.equal(stockScenario('Increase inventory by 25%')[1].stock_multiplier,1.25);
assert.throws(()=>stockScenario('Cut stock by 120%'),/0 to 100/);
assert.equal(stockScenario('What is cleanup NPV?'),null);
assert.equal(resolveContext('Cut stock by 20%',[{role:'user',text:'Material 4100000129'}],{funcloc:'KT-383A'}).funcloc,'KT-383A');
const r=await ask({db,question:'What if we cut stock by 20%?',context:{funcloc:'KT-383A'}});
assert.equal(r.trace.find(t=>t.step==='tool').name,'simulate_scenario');
assert.deepEqual(r.trace.find(t=>t.step==='tool').args,{stock_multiplier:.8,scope:{equipment:'KT-383A'}});
const result=r.tool_results[0].data;
const count=db.prepare("SELECT count(distinct b.material_no) n FROM bom b JOIN funcloc f USING(funcloc) WHERE f.tag=?").get('KT-383A').n;
assert.equal(result.baseline.parts,count);assert.equal(result.scenario.parts,count);
assert.equal(result.scenario.settings.stock_multiplier,.8);
assert(result.scenario.stock_value_idr<result.baseline.stock_value_idr);
assert(result.scenario.expected_stockouts_yr>=result.baseline.expected_stockouts_yr);
assert(!r.trace.some(t=>/cleanup/.test(t.name||'')));
assert(r.answer.includes('KT-383A')&&r.answer.includes('0.8'));
assert.equal(r.charts.length,3);assert.equal(r.charts[0].rows[1].value,result.scenario.stock_value_idr);
assert.equal(r.charts[1].rows[1].value,result.scenario.expected_stockouts_yr);
assert.equal(r.charts[2].rows[1].value,result.scenario.service_level);
const material=await ask({db,question:'Cut stock by 20%',context:{material_no:4100000129}});
assert.equal(material.tool_results[0].data.baseline.parts,1);
assert.deepEqual(material.trace.find(t=>t.step==='tool').args.scope,{material_no:4100000129});
const broad=await ask({db,question:'Cut stock by 20%'});assert.equal(broad.tool_results[0].data.baseline.parts,db.prepare('SELECT count(*) n FROM material').get().n);assert.equal(broad.charts.length,3);
console.log('PASS: stock percentage, equipment/material scope, exact engine comparison and chart values; complete portfolio scope is computed without sampling.');
})().catch(e=>{console.error(e);process.exitCode=1});
